# statements
"""
* a computer program is a list of "instructions" to be "executed" by a computer
* in a program language, these programming instructions are called statements
* the following statement prints the text "Python is fun!" to the screen.
* you do not need to use a semicolon (;) like in many other programming languages
"""

print("Python is fun!")


# many statements
"""
* most python programs contain many statements
* the statements are executed one by one, in the same order as they are written
"""

print("hi")
print("hello")
print("learning python is fun!")


# semicolons (optional, rarely used)
"""
* semicolons are optional in Python
* you can write multiple statements on one line by separating them with ; 
"""

print("123") ; print("456") ; print("789")


