# output variables
"""
* the print() function is often used to output variables
"""

x = "python is awesome"
print(x)

"""
* In the print(), function you output multiple variables, separated by a comma
"""
x = "python"
y = "is"
z = "awesome"
print(x, y, z)

"""
* you can also use the + operator to output multiple variables
"""
x = "python "
