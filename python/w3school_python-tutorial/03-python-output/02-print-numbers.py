# print numbers
"""
* use print() function to display numbers
* do not put numbers inside quotes
* you can do math inside the print() function
"""

print(1)
print(2)
print(1000)

# math
print(1 + 3)
print(3 * 2)


# mix text and numbers
"""
* you can combine text and numbers in one output by separating them with a comma , 
"""

print("I am", 41, "years old.")



