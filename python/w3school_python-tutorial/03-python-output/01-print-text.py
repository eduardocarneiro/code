# print text
"""
* we can use print() function o display text or output values
* print() function can be used as many times as you want
* each call prints text on a new line by default
"""


# double quotes
"""
* text in python must be inside quotes
* you can use either "" double quotes or '' single quotes
"""

print("works!")
print('also works!')


# print without a new line
"""
* by default the print() function ends with a new line
* to print multiple words on the same line, use the 'end' parameter
* NOTE: we add a space after end=" " for better readability
"""

print("print it without new line", end=" ")
print(". It will print on the same line")


